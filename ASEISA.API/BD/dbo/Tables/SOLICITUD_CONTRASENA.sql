CREATE TABLE dbo.SOLICITUD_CONTRASENA (
    id_solicitud BIGINT IDENTITY(1,1) NOT NULL CONSTRAINT PK_SOLICITUD_CONTRASENA PRIMARY KEY,
    id_usuario INT NOT NULL,
    id_empresa INT NOT NULL,
    correo VARCHAR(150) NOT NULL,
    hash_token BINARY(32) NOT NULL,
    version_credencial BIGINT NOT NULL CONSTRAINT DF_SOLICITUD_CONTRASENA_Version DEFAULT 0,
    proposito VARCHAR(20) NOT NULL,
    fecha_creacion DATETIME2(7) NOT NULL CONSTRAINT DF_SOLICITUD_CONTRASENA_Creacion DEFAULT SYSUTCDATETIME(),
    fecha_expiracion DATETIME2(7) NOT NULL,
    fecha_consumo DATETIME2(7) NULL,
    CONSTRAINT FK_SOLICITUD_CONTRASENA_Usuario FOREIGN KEY(id_usuario) REFERENCES dbo.USUARIO(id_usuario),
    CONSTRAINT FK_SOLICITUD_CONTRASENA_Empresa FOREIGN KEY(id_empresa) REFERENCES dbo.EMPRESA(id_empresa),
    CONSTRAINT UQ_SOLICITUD_CONTRASENA_Token UNIQUE(hash_token),
    CONSTRAINT CK_SOLICITUD_CONTRASENA_Proposito CHECK(proposito IN ('Invitacion','Administrativo','Recuperacion')),
    CONSTRAINT CK_SOLICITUD_CONTRASENA_Vigencia CHECK(fecha_expiracion>fecha_creacion)
);
GO
CREATE INDEX IX_SOLICITUD_CONTRASENA_Usuario ON dbo.SOLICITUD_CONTRASENA(id_usuario,fecha_creacion);