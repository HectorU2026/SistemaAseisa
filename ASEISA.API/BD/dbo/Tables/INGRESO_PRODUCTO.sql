CREATE TABLE [dbo].[INGRESO_PRODUCTO] (
    [id_ingreso_producto]        INT             IDENTITY (1, 1) NOT NULL,
    [id_empresa]                 INT             NOT NULL,
    [id_producto]                INT             NOT NULL,
    [id_bodega]                  INT             NOT NULL,
    [id_usuario]                 INT             NOT NULL,
    [id_contacto]                INT             NOT NULL,
    [fecha_entrega]              DATETIME2 (7)   NOT NULL,
    [tipo_operacion]             VARCHAR (50)    NOT NULL,
    [cantidad]                   DECIMAL (18, 4) NOT NULL,
    [cotizacion_compra]          VARCHAR (50)    NULL,
    [id_cotizacion]              INT             NULL,
    [id_distribucion_analitica]  INT             NULL,
    [id_estado]                  INT             NOT NULL,
    [fecha_creacion]             DATETIME2 (7)   DEFAULT (sysdatetime()) NOT NULL,
    CONSTRAINT [PK_INGRESO_PRODUCTO] PRIMARY KEY CLUSTERED ([id_ingreso_producto] ASC),
    CONSTRAINT [CK_INGRESO_PRODUCTO_CANTIDAD] CHECK ([cantidad]>=(0)),
    CONSTRAINT [CK_INGRESO_PRODUCTO_TIPO] CHECK ([tipo_operacion]='recepcion' OR [tipo_operacion]='entrega'),
    CONSTRAINT [FK_INGRESO_PRODUCTO_EMPRESA] FOREIGN KEY ([id_empresa]) REFERENCES [dbo].[EMPRESA] ([id_empresa]),
    CONSTRAINT [FK_INGRESO_PRODUCTO_PRODUCTO] FOREIGN KEY ([id_producto]) REFERENCES [dbo].[PRODUCTO] ([id_producto]),
    CONSTRAINT [FK_INGRESO_PRODUCTO_BODEGA] FOREIGN KEY ([id_bodega]) REFERENCES [dbo].[BODEGA] ([id_bodega]),
    CONSTRAINT [FK_INGRESO_PRODUCTO_USUARIO] FOREIGN KEY ([id_usuario]) REFERENCES [dbo].[USUARIO] ([id_usuario]),
    CONSTRAINT [FK_INGRESO_PRODUCTO_CONTACTO] FOREIGN KEY ([id_contacto]) REFERENCES [dbo].[CONTACTO] ([id_contacto]),
    CONSTRAINT [FK_INGRESO_PRODUCTO_COTIZACION] FOREIGN KEY ([id_cotizacion]) REFERENCES [dbo].[COTIZACION] ([id_cotizacion]),
    CONSTRAINT [FK_INGRESO_PRODUCTO_DISTRIBUCION] FOREIGN KEY ([id_distribucion_analitica]) REFERENCES [dbo].[DISTRIBUCION_ANALITICA] ([id_distribucion_analitica]),
    CONSTRAINT [FK_INGRESO_PRODUCTO_ESTADO] FOREIGN KEY ([id_estado]) REFERENCES [dbo].[ESTADO] ([id_estado])
);
